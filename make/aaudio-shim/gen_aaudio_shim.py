#!/usr/bin/env python3
"""Generate aaudio_shim.c from the NDK's aaudio/AAudio.h.

The shim defines every AAUDIO_API function as a forwarder that resolves the
real symbol from libaaudio.so with dlopen/dlsym on first use. Linking it as a
static libaaudio.a lets a library built against API 21 use cpal's AAudio
backend: on Android 8+ calls reach the system library, on older devices they
fail with AAUDIO_ERROR_UNAVAILABLE instead of the .so refusing to load.

Usage: gen_aaudio_shim.py <path/to/AAudio.h> <out.c>
"""
import re
import sys

header_path, out_path = sys.argv[1], sys.argv[2]
text = open(header_path).read()
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
text = re.sub(r"//[^\n]*", "", text)
text = re.sub(r"^\s*#.*$", "", text, flags=re.M)

decls = re.findall(r"AAUDIO_API\s+(.*?);", text, flags=re.S)
funcs = []
for decl in decls:
    decl = re.sub(r"__[A-Z_]+\([^)]*\)", "", decl)
    decl = re.sub(r"\b_Nonnull\b|\b_Nullable\b", "", decl)
    decl = " ".join(decl.split())
    m = re.match(r"(.+?)\b(\w+)\s*\((.*)\)\s*$", decl)
    if not m:
        sys.exit(f"cannot parse: {decl}")
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
    if params in ("", "void"):
        plist = []
    else:
        plist = [p.strip() for p in params.split(",")]
    names = []
    for p in plist:
        pm = re.search(r"(\w+)\s*$", p)
        if not pm:
            sys.exit(f"cannot parse param: {p} in {name}")
        names.append(pm.group(1))
    funcs.append((ret, name, plist, names))

def default_return(ret):
    r = ret.replace(" ", "")
    if r == "void":
        return None
    if r == "aaudio_result_t":
        return "AAUDIO_ERROR_UNAVAILABLE"
    if "char*" in r:
        return '"AAudio unavailable"'
    if "*" in r:
        return "NULL"
    if r == "bool":
        return "false"
    return "0"

out = []
out.append("// Generated by gen_aaudio_shim.py from aaudio/AAudio.h. Do not edit.")
out.append("// Forwards every AAudio entry point to libaaudio.so, resolved at runtime.")
out.append("#include <aaudio/AAudio.h>")
out.append("#include <dlfcn.h>")
out.append("#include <pthread.h>")
out.append("#include <stdbool.h>")
out.append("#include <stddef.h>")
out.append("")
out.append("static void *aaudio_shim_handle;")
out.append("static pthread_once_t aaudio_shim_once = PTHREAD_ONCE_INIT;")
out.append("")
out.append("static void aaudio_shim_open(void) {")
out.append('    aaudio_shim_handle = dlopen("libaaudio.so", RTLD_NOW | RTLD_LOCAL);')
out.append("}")
out.append("")
out.append("static void *aaudio_shim_sym(const char *name) {")
out.append("    pthread_once(&aaudio_shim_once, aaudio_shim_open);")
out.append("    return aaudio_shim_handle ? dlsym(aaudio_shim_handle, name) : NULL;")
out.append("}")
out.append("")
for ret, name, plist, names in funcs:
    ptypes = ", ".join(plist) if plist else "void"
    sig = f"{ret} {name}({ptypes})"
    fnty = f"{ret} (*)({ptypes})"
    dflt = default_return(ret)
    out.append(sig + " {")
    out.append(f"    static {ret} (*fn)({ptypes});")
    out.append(f'    if (!fn) fn = ({fnty})aaudio_shim_sym("{name}");')
    if dflt is None:
        out.append("    if (!fn) return;")
        out.append(f"    fn({', '.join(names)});")
    else:
        out.append(f"    if (!fn) return {dflt};")
        out.append(f"    return fn({', '.join(names)});")
    out.append("}")
    out.append("")
open(out_path, "w").write("\n".join(out))
print(f"{len(funcs)} functions")
